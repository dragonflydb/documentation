@dataclass
class PageResult:
    path: Path
    command: str | None = None
    status: str = ""           # updated | unchanged | not-synced | failed | llm-skip
    reason: str = ""
    old: list[str] = field(default_factory=list)
    new: list[str] = field(default_factory=list)
    via: str = "mechanical"    # mechanical | llm
    expected: list[str] = field(default_factory=list)
    kind: str = ""             # own | acl-only | inherited | routed
    key: str | None = None     # the entry whose categories apply
    llm_eligible: bool = False
    new_text: str | None = None

    def tag(self) -> str:
        if self.kind == "acl-only":
            return f"[acl-only {self.key}]"
        if self.kind == "inherited":
            return f"[inherited from {self.key}]"
        if self.kind == "routed":
            return f"[routed -> {self.key}]"
        return f"[{self.kind}]" if self.kind else ""


@dataclass
class CategoriesPage:
    status: str = ""           # updated | unchanged | skipped | failed
    reason: str = ""
    new_text: str | None = None


