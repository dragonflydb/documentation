#!/usr/bin/env python3
"""acl_sync.py — Synchronize ACL category lines in command-reference docs.

Reads the ACL categories captured from a Dragonfly Docker image (dfly_facts.py)
and updates the `**ACL categories:**` line of every command-reference page
whose H1 is a server command. The categories shown are those of the entry the
server checks for that command (acl_model.py): its own entry, an ACL-only
subcommand entry (CLIENT KILL), the container's entry for other subcommands,
or a routed hidden command (XGROUP HELP). Pages Docusaurus does not publish (a
path component starting with `_`) are not processed. It also regenerates the
command lists of docs/managing-dragonfly/acl-categories.md.

Order of a run; nothing is written before the last step:
  1. facts shape checks (exit 4 on a violation);
  2. every page is resolved and its new text computed;
  3. live check: ACL DRYRUN on the facts image for every page (exit 3 on any
     disagreement; skip with --no-verify-live);
  4. LLM repair of pages without a usable ACL line (OPENAI_API_KEY);
  5. pages are written (not with --dry-run).

Updates are minimal-diff: a page whose set of categories already matches is
not touched; otherwise kept categories keep their order, new ones are appended
alphabetically and removed ones dropped.

Exit codes: 0 ok; 1 pages failed or need confirmation; 2 facts could not be
loaded or an unexpected error; 3 live check failed; 4 facts shape check failed.

Usage:
    python tools/docsync/acl_sync.py --tag v2.1.0
    python tools/docsync/acl_sync.py --tag v2.1.0 --dry-run
    python tools/docsync/acl_sync.py --facts tools/generated/facts/v2.1.0.json
    python tools/docsync/acl_sync.py --tag v2.1.0 --filter "search/*"
"""

